const {contextBridge, ipcRenderer} = require('electron');
contextBridge.exposeInMainWorld('callDesk', {
  copyText:text=>ipcRenderer.invoke('clipboard:write',text),
  reportError:error=>ipcRenderer.send('diagnostics:error',error),
  reportHealth:value=>ipcRenderer.send('diagnostics:health',value),
  introductionStatus:()=>ipcRenderer.invoke('introduction:status'),
  introductionDismiss:kind=>ipcRenderer.invoke('introduction:dismiss',kind),
  onIntroductionOpen:callback=>ipcRenderer.on('introduction:open',(_event,kind)=>callback(kind)),
  calendarStatus:()=>ipcRenderer.invoke('calendar:status'),
  calendarConnect:()=>ipcRenderer.invoke('calendar:connect'),
  calendarEvents:()=>ipcRenderer.invoke('calendar:events'),
  calendarDisconnect:()=>ipcRenderer.invoke('calendar:disconnect'),
  settingsStatus:()=>ipcRenderer.invoke('settings:status'),
  setAppearance:source=>ipcRenderer.invoke('settings:appearance',source),
  setReminder:seconds=>ipcRenderer.invoke('settings:reminder',seconds),
  setDetection:mode=>ipcRenderer.invoke('settings:detection',mode),
  onSettingsChanged:callback=>ipcRenderer.on('settings:changed',(_event,state)=>callback(state)),
  onSettingsOpen:callback=>ipcRenderer.on('settings:open',(_event,section)=>callback(section)),
  mcpSetup:()=>ipcRenderer.invoke('mcp:setup'),
  mcpDocs:id=>ipcRenderer.invoke('mcp:docs',id),
  exportDiagnostics:()=>ipcRenderer.invoke('settings:export-diagnostics'),
  updateStatus:()=>ipcRenderer.invoke('updates:status'),
  updateCheck:()=>ipcRenderer.invoke('updates:check'),
  updateInstall:()=>ipcRenderer.invoke('updates:install'),
  updateDownloads:()=>ipcRenderer.invoke('updates:downloads'),
  onUpdateState:callback=>ipcRenderer.on('updates:state',(_event,state)=>callback(state)),
  onUpdateOpen:callback=>ipcRenderer.on('updates:open',()=>callback()),
  menuState:state=>ipcRenderer.send('tray:state',state),
  onMenuStart:callback=>ipcRenderer.on('tray:start',()=>callback()),
  onMenuStop:callback=>ipcRenderer.on('tray:stop',()=>callback()),
  onDetectedStart:callback=>ipcRenderer.on('detection:start',(_event,request)=>callback(request)),
  detectedResult:result=>ipcRenderer.send('detection:result',result),
  session:()=>ipcRenderer.invoke('session'),
  microphone:()=>ipcRenderer.invoke('microphone'),
  recording:value=>ipcRenderer.send('recording', !!value)
});
